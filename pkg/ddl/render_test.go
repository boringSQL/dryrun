// The strings being checked are mostly Postgres' own deparse output, so on a
// newer server a parse failure means the grammar is old, not the SQL wrong.
func TestParseGateYieldsToANewerServer(t *testing.T) {
	tab := tbl("t", col("a", "integer"))
	tab.Constraints = []snapshot.Constraint{
		{Name: "c", Kind: snapshot.ConstraintPrimaryKey, Definition: sp("PRIMARY KEY (a, valid_at WITHOUT OVERLAPS)")},
	}

	t.Run("newer than the parser", func(t *testing.T) {
		r, err := RenderTable(&snapshot.SchemaSnapshot{PgVersion: "18.3.0", Tables: []snapshot.Table{*tab}}, tab)
		if err != nil {
			t.Fatalf("a pg18 snapshot was denied its ddl: %v", err)
		}
		if r.ParseChecked || r.ParseError == "" {
			t.Errorf("should say it could not check: %+v", r)
		}
	})

	t.Run("same as the parser", func(t *testing.T) {
		if _, err := RenderTable(&snapshot.SchemaSnapshot{PgVersion: "17.2", Tables: []snapshot.Table{*tab}}, tab); err == nil {
			t.Error("unparseable ddl from a pg17 snapshot was returned")
		}
	})
}

