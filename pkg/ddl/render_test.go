// The order is the contract for anything diffing statement by statement.
func TestStatementOrder(t *testing.T) {
	tab := tbl("t", col("a", "integer"))
	tab.Comment = sp("c")
	tab.Constraints = []snapshot.Constraint{
		{Name: "fk", Kind: snapshot.ConstraintForeignKey, Definition: sp("FOREIGN KEY (a) REFERENCES u(b)")},
	}
	tab.Indexes = []snapshot.Index{{Name: "i", Definition: "CREATE INDEX i ON public.t USING btree (a)"}}

	got := render(t, nil, tab).Statements
	want := []string{"CREATE TABLE ", "ALTER TABLE public.t ADD CONSTRAINT fk", "CREATE INDEX i", "COMMENT ON TABLE"}
	if len(got) != len(want) {
		t.Fatalf("got %d statements, want %d: %v", len(got), len(want), got)
	}
	for i := range want {
		if !strings.HasPrefix(got[i], want[i]) {
			t.Errorf("statement %d = %q, want prefix %q", i, got[i], want[i])
		}
	}
}
