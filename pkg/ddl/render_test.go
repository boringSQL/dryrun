func sp(s string) *string { return &s }

func col(name, typ string) snapshot.Column {
	return snapshot.Column{Name: name, TypeName: typ, Nullable: true}
}

func tbl(name string, cols ...snapshot.Column) *snapshot.Table {
	return &snapshot.Table{Schema: "public", Name: name, Columns: cols}
}

func render(t *testing.T, snap *snapshot.SchemaSnapshot, tab *snapshot.Table) *Result {
	t.Helper()
	r, err := RenderTable(snap, tab)
	if err != nil {
		t.Fatalf("RenderTable: %v", err)
	}
	return r
}

func TestRenderColumns(t *testing.T) {
	notNull := func(c snapshot.Column) snapshot.Column { c.Nullable = false; return c }

	tests := []struct {
		name string
		col  snapshot.Column
		want string
	}{
		{"plain", col("a", "integer"), "a integer"},
		{"not null", notNull(col("a", "integer")), "a integer NOT NULL"},
		{"default", func() snapshot.Column { c := col("a", "integer"); c.Default = sp("42"); return c }(), "a integer DEFAULT 42"},
		{"identity always", func() snapshot.Column {
			c := notNull(col("id", "bigint"))
			c.Identity = sp("always")
			return c
		}(), "id bigint GENERATED ALWAYS AS IDENTITY NOT NULL"},
		{"identity by default", func() snapshot.Column {
			c := notNull(col("id", "bigint"))
			c.Identity = sp("by_default")
			return c
		}(), "id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"},
		{"generated stored", func() snapshot.Column {
			c := col("b", "integer")
			c.Generated, c.GenerationExpr = sp("stored"), sp("(a * 2)")
			return c
		}(), "b integer GENERATED ALWAYS AS ((a * 2)) STORED"},
		{"quoted name", col("Odd Name", "text"), `"Odd Name" text`},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			r := render(t, nil, tbl("t", snapshot.Column{Name: "a", TypeName: "integer", Nullable: true}, tc.col))
			if !strings.Contains(r.SQL, tc.want) {
				t.Errorf("want %q in:\n%s", tc.want, r.SQL)
			}
		})
	}
}

// A generation expression is not a default, and PG18 defaults it to VIRTUAL.
// The bundled parser is PG17, so the syntax check has to allow for that without
// changing what is emitted.
func TestRenderVirtualGeneratedColumn(t *testing.T) {
	c := col("b", "integer")
	c.Generated, c.GenerationExpr = sp("virtual"), sp("(a * 2)")

	r := render(t, nil, tbl("t", col("a", "integer"), c))
	if !strings.Contains(r.SQL, "GENERATED ALWAYS AS ((a * 2)) VIRTUAL") {
		t.Errorf("virtual rendered as something else:\n%s", r.SQL)
	}
	if strings.Contains(r.SQL, "STORED") {
		t.Errorf("the parser workaround leaked into the output:\n%s", r.SQL)
	}
}

func TestRenderConstraintsAndIndexes(t *testing.T) {
	tab := tbl("orders", col("id", "bigint"), col("user_id", "bigint"))
	tab.Constraints = []snapshot.Constraint{
		{Name: "orders_pkey", Kind: snapshot.ConstraintPrimaryKey, Definition: sp("PRIMARY KEY (id)")},
		{Name: "orders_total_check", Kind: snapshot.ConstraintCheck, Definition: sp("CHECK (id > 0)")},
		{Name: "orders_user_fkey", Kind: snapshot.ConstraintForeignKey, Definition: sp("FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE")},
	}
	tab.Indexes = []snapshot.Index{
		// the constraint creates this one; emitting it again fails on the name
		{Name: "orders_pkey", IsPrimary: true, Definition: "CREATE UNIQUE INDEX orders_pkey ON public.orders USING btree (id)"},
		{Name: "orders_user_id_idx", Definition: "CREATE INDEX orders_user_id_idx ON public.orders USING btree (user_id)"},
	}

	r := render(t, nil, tab)
	for _, want := range []string{
		"CONSTRAINT orders_pkey PRIMARY KEY (id)",
		"CONSTRAINT orders_total_check CHECK (id > 0)",
		// after the table, so the referenced table can exist first
		"ALTER TABLE public.orders ADD CONSTRAINT orders_user_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;",
		"CREATE INDEX orders_user_id_idx",
	} {
		if !strings.Contains(r.SQL, want) {
			t.Errorf("missing %q in:\n%s", want, r.SQL)
		}
	}
	if strings.Contains(r.SQL, "CREATE UNIQUE INDEX orders_pkey") {
		t.Errorf("emitted the constraint's own index:\n%s", r.SQL)
	}
	// inside CREATE TABLE it would demand the referenced table already exist
	if strings.Contains(r.Statements[0], "FOREIGN KEY") {
		t.Errorf("foreign key rendered inside CREATE TABLE:\n%s", r.Statements[0])
	}
}

